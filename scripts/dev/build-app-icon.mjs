/* Writes public/images/brand/app-icon.svg from the shared geometry.
 *
 * The icon's shapes are the mascot's own curves (src/lib/hoopoe-geometry.ts,
 * lifted from src/components/mascot/hoopoe.tsx), so the mark follows the
 * character rather than being a copy of it that quietly falls behind. The lab
 * rooms render the identical Prim[] through React; this renders it to markup.
 *
 * No dev server, no sign-in, no browser: Node strips the types and the module
 * has no JSX in it, which is the whole reason the geometry is data.
 *
 *   node scripts/dev/build-app-icon.mjs
 *   node scripts/dev/generate-icons.mjs
 */
import { writeFileSync, readFileSync } from "node:fs";
import { G, PEEK_VIEW, peekPrims, primsToSvg } from "../../src/lib/hoopoe-geometry.ts";

const OUT = "public/images/brand/app-icon.svg";
const SCALE = 512 / PEEK_VIEW.size;

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512" role="img" aria-label="Hoopoe">
  <!--
    The app icon: the hoopoe peeking over the bottom edge of the tile.

    GENERATED by scripts/dev/build-app-icon.mjs. Do not hand-edit; the
    geometry is src/lib/hoopoe-geometry.ts, which is the mascot's own curves.

    This is NOT what a browser tab shows. src/app/icon.svg is still the hills,
    on purpose: a tab is 16px of chrome beside a page title and wants the quiet
    mark, while an icon on a home screen is looked at.

    One canopy tile, and no dark variant. This file used to carry a
    prefers-color-scheme rule that swapped the tile to ink, which did nothing:
    the only thing that reads this file is generate-icons.mjs, and sharp
    rasterises without a colour scheme, so every PNG came out canopy anyway.
    Nor could it work downstream. A home screen icon is one flat PNG on both
    platforms: iOS reads apple-touch-icon, and a web manifest icon entry
    carries src, sizes, type and purpose and nothing that varies by appearance.
    A rule that quietly does nothing is worse than no rule, so it is gone.

    The empty defs#fx and the g#lit wrapper around the art are the two seams
    generate-icons.mjs fills in to bake Apple's edge light into the Android
    build. The Apple build gets this file untouched, because iOS 26 and macOS
    26 add their own specular pass and doubling it would show.

    Those two are named here without their angle brackets on purpose: the
    generator finds them by string replace, and a comment that spelled the tags
    out got substituted into instead of the markup.
  -->
  <rect width="512" height="512" rx="96" fill="${G.canopy}" />
  <defs id="fx"></defs>
  <g id="lit">
    <g transform="translate(${(-PEEK_VIEW.x * SCALE).toFixed(3)} ${(-PEEK_VIEW.y * SCALE).toFixed(3)}) scale(${SCALE.toFixed(5)})">${primsToSvg(peekPrims())}</g>
  </g>
</svg>
`;

/* Assert the seams here rather than only in generate-icons.mjs: a silently
   flat Android icon is the failure this whole path exists to prevent, and it
   is far easier to see at the point the file is written. */
for (const seam of ['<defs id="fx"></defs>', '<g id="lit">']) {
  if (!svg.includes(seam)) {
    console.error(`build-app-icon: no longer emitting ${seam}. generate-icons.mjs needs it.`);
    process.exit(1);
  }
}

const before = (() => { try { return readFileSync(OUT, "utf8"); } catch { return ""; } })();
writeFileSync(OUT, svg);
console.log(`${OUT}  ${svg.length} bytes${before === svg ? " (unchanged)" : ""}`);
